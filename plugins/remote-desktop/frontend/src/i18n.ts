export type T = (key: string, vars?: Record<string, string | number>) => string

export function makeT(lang: string): T {
  const dict: Record<string, string> = lang.toLowerCase().startsWith('en') ? EN : KO
  return (key, vars) => {
    let s = dict[key] ?? (KO as Record<string, string>)[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

export function hasKey(key: string): boolean {
  return key in KO
}

export function currentLang(): string {
  return (typeof document !== 'undefined' && document.documentElement.lang) || (typeof navigator !== 'undefined' ? navigator.language : 'ko') || 'ko'
}

/** 바이트 → "8.3 MB" */
export function fmtSize(bytes: number): string {
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
}

/** ISO → "MM-DD HH:mm"(시안 표기) */
export function fmtWhen(iso: string | null): string {
  if (!iso) return '—'
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return '—'
  const p = (n: number) => String(n).padStart(2, '0')
  return `${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`
}

/** 초 → "m:ss" / "h:mm:ss" */
export function fmtDuration(sec: number | null): string {
  if (sec == null || sec < 0) return '—'
  const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = Math.floor(sec % 60)
  const p = (n: number) => String(n).padStart(2, '0')
  return h ? `${h}:${p(m)}:${p(s)}` : `${m}:${p(s)}`
}
